def psql(region: str, sql: str) -> list[list[str]]:
    """Run SQL in a region's database, as the server's local superuser, inside the instance pod."""
    sys.path.insert(0, str(ROOT / "src"))
    from atlas_realms.regions import db_name

    out = kubectl(
        "-n", NAMESPACE, "exec", "realms-db-1", "-c", "postgres", "--",
        "psql", "-d", db_name(region), "-v", "ON_ERROR_STOP=1", "-qtAF", "\t", "-c", sql,
    )  # fmt: skip
    return [line.split("\t") for line in out.splitlines() if line]


def wait_for(what: str, fn, timeout: float, every: float = 5.0):
    deadline = time.monotonic() + timeout
    while True:
        with contextlib.suppress(Exception):  # not yet: keep polling until the deadline, then report what failed
            result = fn()
            if result:
                print(f"ok: {what}")
                return result
        if time.monotonic() > deadline:
            raise SystemExit(f"FAILED: {what} (after {timeout:.0f} s)")
        time.sleep(every)


def http_json(url: str) -> tuple[int, dict]:
    try:
        with urllib.request.urlopen(url, timeout=10) as resp:
            return resp.status, json.load(resp)
    except urllib.error.HTTPError as e:
        return e.code, json.load(e)


def ticks(port: int) -> dict[str, int]:
    status, body = http_json(f"http://127.0.0.1:{port}/api/world")
    return {r["id"]: r["tick"] for r in body["regions"]} if status == 200 else {}


def scripted_order(region: str) -> tuple[int, int]:
    """A test player on the region's first spawn hex, ordered to walk to a neighbouring land hex. Returns (user, order)."""
    import h3

    spawn = psql(region, "SELECT h3::text FROM hexes WHERE zone = 'spawn' AND playable ORDER BY h3 LIMIT 1")[0][0]
    land = {r[0] for r in psql(region, "SELECT h3::text FROM hexes WHERE zone = 'land' AND playable")}
    target = sorted(set(h3.grid_ring(spawn, 1)) & land)[0]
    name = f"smoke-{secrets.token_hex(4)}"
    user = int(
        psql(
            region,
            f"INSERT INTO users (oauth_provider, oauth_subject, display_name) VALUES ('smoke', '{name}', '{name}') "
            "RETURNING id",
        )[0][0]
    )
    psql(region, f"INSERT INTO units (user_id, hex, hp) VALUES ({user}, '{spawn}', 100)")
    order = int(
        psql(
            region,
            f"INSERT INTO orders (user_id, kind, payload) VALUES ({user}, 'move', '{{\"to\": \"{target}\"}}') RETURNING id",
        )[0][0]
    )
    print(f"scripted order {order}: player {user} in {region}, {spawn} -> {target}")
    return user, order


def unit_state(region: str, user: int) -> tuple[str, float, int]:
    hex_, progress, path_len = psql(
        region, f"SELECT hex::text, progress, cardinality(path) FROM units WHERE user_id = {user}"
    )[0]
    return hex_, float(progress), int(path_len)


def netpol_refuses_strangers(app_image: str) -> None:
    """A pod without the db-client label must not reach Postgres; one with it must.

    The policy controller admits a new pod's address a moment after the pod starts (k3s's kube-router syncs on pod
    events), so each probe tries for a minute: the labelled one must get through, the stranger never may.
    """
    probe = (
        "import socket, time\n"
        "for _ in range(20):\n"
        "    try:\n"
        "        socket.create_connection(('realms-db-rw', 5432), timeout=3).close()\n"
        "        print('PROBE=reached')\n"
        "        break\n"
        "    except OSError:\n"
        "        time.sleep(2)\n"
        "else:\n"
        "    print('PROBE=refused')\n"
    )

    def reach(name: str, labelled: bool) -> str:
        labels = "realms.dragonhound.dev/db-client=true" if labelled else "realms.dragonhound.dev/probe=true"
        r = subprocess.run(
            [
                "kubectl", "-n", NAMESPACE, "run", name, "--rm", "-i", "--restart=Never", "--quiet",
                f"--image={app_image}", "--image-pull-policy=IfNotPresent", f"--labels={labels}",
                "--overrides", json.dumps({"spec": {"automountServiceAccountToken": False}}),
                "--command", "--", "python", "-c", probe,
            ],
            capture_output=True, text=True, timeout=180,
        )  # fmt: skip
        return next((line.split("=", 1)[1] for line in r.stdout.splitlines() if line.startswith("PROBE=")), r.stderr)

    if reach("np-probe-labelled", True) != "reached":
        raise SystemExit("FAILED: a db-client pod could not reach Postgres")
    print("ok: a db-client pod reaches Postgres")
    if reach("np-probe-stranger", False) != "refused":
        raise SystemExit("FAILED: a pod without the db-client label reached Postgres (is NetworkPolicy enforced?)")
    print("ok: a pod without the db-client label can't reach Postgres")


def cmd_smoke(a: argparse.Namespace) -> int:
    regions = read_regions(a.overlay)
    first = regions[0]
    pf = subprocess.Popen(
        ["kubectl", "-n", NAMESPACE, "port-forward", "service/realms-api", f"{a.port}:80"],
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    try:
        body = wait_for(
            "API healthy",
            lambda: (s := http_json(f"http://127.0.0.1:{a.port}/health"))[0] == 200 and s[1]["status"] == "ok" and s[1],
            120,
            2,
        )
        assert set(body["regions"]) == set(regions), body["regions"]
        before = wait_for("every region has ticked", lambda: (t := ticks(a.port)) and min(t.values()) > 0 and t, 300)
        wait_for(
            "every region keeps ticking",
            lambda: (t := ticks(a.port)) and all(t[r] > before[r] for r in regions),
            200,
        )

        user, order = scripted_order(first)
        wait_for(
            f"order {order} applied in {first}",
            lambda: (
                psql(first, f"SELECT applied_tick IS NOT NULL AND result = 'ok' FROM orders WHERE id = {order}")[0][0]
                == "t"
            ),
            200,
        )
        start = wait_for(f"the player in {first} is walking", lambda: (u := unit_state(first, user))[2] > 0 and u, 200)

        # Kill the region's worker mid-game: the next one must carry on from the database, nothing lost or repeated.
        tick_before = ticks(a.port)[first]
        pods = kubectl(
            "-n", NAMESPACE, "get", "pods", "-o", "name",
            "-l", f"app.kubernetes.io/name=realms-tick,realms.dragonhound.dev/region={first}",
        ).split()  # fmt: skip
        kubectl("-n", NAMESPACE, "delete", *pods, "--grace-period=0", "--force", "--wait=true", timeout=180)
        print(f"killed {' '.join(pods)} at tick {tick_before}")
        kubectl("-n", NAMESPACE, "rollout", "status", f"deployment/realms-tick-{first}", "--timeout=300s")
        wait_for(f"{first} ticks again after the kill", lambda: ticks(a.port)[first] > tick_before + 1, 300)
        rows = psql(
            first,
            "SELECT count(*), count(*) FILTER (WHERE finished_at IS NULL), max(id) - min(id) + 1 FROM ticks",
        )[0]
        assert rows[1] == "0" and rows[0] == rows[2], f"ticks not contiguous and finished: {rows}"
        assert psql(first, f"SELECT count(*) FROM orders WHERE user_id = {user}")[0][0] == "1"
        after = unit_state(first, user)
        moved = after[0] != start[0] or after[1] > start[1]
        assert moved, f"the player's walk did not resume: {start} -> {after}"
        print(
            f"ok: {first} resumed from the database ({rows[0]} contiguous ticks, the walk went on: {start} -> {after})"
        )
        print("ok: other regions untouched: " + json.dumps(ticks(a.port)))
    finally:
        pf.terminate()
        pf.wait(timeout=10)

    app_image = kubectl(
        "-n", NAMESPACE, "get", "deployment", "realms-api", "-o", "jsonpath={.spec.template.spec.containers[0].image}"
    )  # fmt: skip
    netpol_refuses_strangers(app_image)
    print("smoke test passed")
    return 0


def main() -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--overlay", type=Path, default=OVERLAY, help="The overlay with regions.txt (default: dev)")
    sub = p.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("regions", help="Generate the overlay's regions.yaml from regions.txt")
    r.add_argument("--check", action="store_true", help="Exit 1 if the committed regions.yaml is stale")
    r.set_defaults(fn=cmd_regions)
    pin = sub.add_parser("pin", help="Tag the :build images by image id and write a pinned kustomization")
    pin.add_argument("--out", type=Path, default=PINNED)
    pin.set_defaults(fn=cmd_pin)
    d = sub.add_parser("deploy", help="Install CloudNativePG, the db Secret if missing, and the stack; wait for it")
    d.add_argument("--kustomization", type=Path, default=PINNED)
    d.set_defaults(fn=cmd_deploy)
    s = sub.add_parser("smoke", help="Smoke test a deployed stack")
    s.add_argument("--port", type=int, default=18110, help="Local port for the API's port-forward")
    s.set_defaults(fn=cmd_smoke)
    a = p.parse_args()
    a.overlay = a.overlay.resolve()
    return a.fn(a)


if __name__ == "__main__":
    sys.exit(main())
